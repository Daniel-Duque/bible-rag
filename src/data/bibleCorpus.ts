// Helper to normalize vector to unit length
function norm(v: number[]): number[] {
  const sum = Math.sqrt(v.reduce((acc, val) => acc + val * val, 0));
  return sum === 0 ? v : v.map((x) => Number((x / sum).toFixed(4)));
}

